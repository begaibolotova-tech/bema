// blocks = pairs of lines (each pair is one printed block on the page)
export function blocksOf(page) { const L = BLOCKS[page] || []; const out = []; for (let i = 0; i < L.length; i += 2) out.push(L.slice(i, i + 2)); return out; }
export const WRITE_CPS = 50;   // letters per second while writing in
export function blockTimes(lines) {
  const n = lines.join('').replace(/\s/g, '').length;
  const write = Math.max(0.8, n / WRITE_CPS), hold = n / 15 + 1.5 + write * 0.5 - write;   // visible ≥ letters ÷ 15 + 1.5 s (+ half the writing)
  return { write, hold, dur: write + hold + 0.35 };
}
